BEGIN;
CREATE TABLE IF NOT EXISTS public.internal_procedures (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  title text NOT NULL,
  question text NOT NULL,
  answer text NOT NULL,
  intent text NOT NULL,
  scope text NOT NULL CHECK (scope IN ('GENERAL','SOCIAL_WORK','IMED','PAMI_IMED')),
  social_work_id bigint REFERENCES public.social_works(id),
  billing_channel_id smallint REFERENCES public.billing_channels(id),
  source_document text NOT NULL,
  source_pages text,
  review_notes text,
  status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','APPROVED','ARCHIVED')),
  active boolean NOT NULL DEFAULT false,
  valid_from date,
  valid_to date,
  approved_by uuid,
  approved_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT internal_procedures_approved_chk CHECK (
    NOT (status='APPROVED' AND active=true) OR
    (approved_by IS NOT NULL AND approved_at IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS internal_procedures_intent_idx ON public.internal_procedures(intent,status,active);
