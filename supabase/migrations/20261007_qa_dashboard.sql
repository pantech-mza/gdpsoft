-- GDPSoft QA interno + separación Piloto cliente
-- 2026-10-07

create extension if not exists pgcrypto;

create table if not exists public.assistant_qa_runs (
  id uuid primary key default gen_random_uuid(),
  suite text not null,
  name text not null,
  model text,
  status text not null default 'RUNNING',
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  total_cases integer not null default 0,
  passed integer not null default 0,
  failed integer not null default 0,
  warnings integer not null default 0,
  errors integer not null default 0,
  avg_ms integer,
  p95_ms integer,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_assistant_qa_runs_started_at on public.assistant_qa_runs(started_at desc);
create index if not exists idx_assistant_qa_runs_suite on public.assistant_qa_runs(suite);

create table if not exists public.assistant_qa_results (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.assistant_qa_runs(id) on delete cascade,
  case_id text not null,
  suite text not null,
  category text,
  social_work_id bigint references public.social_works(id) on delete set null,
  normative_id bigint references public.normatives(id) on delete set null,
  image_id uuid null,
  question text,
  expected jsonb not null default '{}'::jsonb,
  actual jsonb not null default '{}'::jsonb,
  route text,
  source text,
  model text,
  elapsed_ms integer,
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  status text not null,
  score numeric(5,2),
  failure_reason text,
  created_at timestamptz not null default now()
);

create index if not exists idx_assistant_qa_results_run on public.assistant_qa_results(run_id);
create index if not exists idx_assistant_qa_results_suite on public.assistant_qa_results(suite);
create index if not exists idx_assistant_qa_results_status on public.assistant_qa_results(status);
create index if not exists idx_assistant_qa_results_created_at on public.assistant_qa_results(created_at desc);

-- El piloto del cliente queda separado de QA y de pruebas históricas.
alter table if exists public.assistant_query_log
  add column if not exists traffic_type text not null default 'OTHER',
  add column if not exists qa_run_id uuid null,
  add column if not exists qa_case_id text null;

alter table if exists public.assistant_quality_event
  add column if not exists traffic_type text not null default 'OTHER';

create index if not exists idx_assistant_query_log_traffic_type on public.assistant_query_log(traffic_type);
create index if not exists idx_assistant_quality_event_traffic_type on public.assistant_quality_event(traffic_type);
