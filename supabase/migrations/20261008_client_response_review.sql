insert into public.modules (code, name, active)
values ('CLIENT_REVIEW', 'Validación de respuestas', true)
on conflict (code)
do update set
  name = excluded.name,
  active = true;

create table if not exists public.client_response_reviews (
  id bigint generated by default as identity primary key,
  qa_result_id bigint not null references public.assistant_qa_results(id) on delete cascade,
  reviewer_profile_id uuid not null references public.profiles(id) on delete cascade,
  verdict text not null check (verdict in ('CORRECT','INCORRECT','PARTIAL')),
  suggested_answer text null,
  comment text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (qa_result_id, reviewer_profile_id)
);

create index if not exists idx_client_response_reviews_result
  on public.client_response_reviews(qa_result_id);

create index if not exists idx_client_response_reviews_reviewer
  on public.client_response_reviews(reviewer_profile_id);

create index if not exists idx_client_response_reviews_verdict
  on public.client_response_reviews(verdict);

