create table if not exists public.social_work_contacts (
  id bigint generated by default as identity primary key,
  social_work_id bigint not null references public.social_works(id) on delete cascade,
  name text not null,
  department text,
  phone text,
  email text,
  notes text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists sw_contacts_sw_idx on public.social_work_contacts(social_work_id);

create table if not exists public.social_work_billing_files (
  id bigint generated by default as identity primary key,
  social_work_id bigint not null references public.social_works(id) on delete cascade,
  title text not null,
  description text,
  file_name text not null,
  storage_path text not null unique,
  mime_type text,
  bytes bigint,
  created_at timestamptz not null default now()
);
create index if not exists sw_billing_files_sw_idx on public.social_work_billing_files(social_work_id);

alter table public.social_work_contacts enable row level security;
alter table public.social_work_billing_files enable row level security;
-- Sin políticas de acceso público: las APIs del servidor validan roles y usan service role.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('gdp-billing-files', 'gdp-billing-files', false, 52428800, array['application/pdf','video/mp4','video/webm'])
on conflict (id) do nothing;
