alter table if exists public.assistant_query_log
  add column if not exists user_id uuid null,
  add column if not exists conversation_id uuid null,
  add column if not exists image_id uuid null,
  add column if not exists model text null,
  add column if not exists has_image boolean not null default false,
  add column if not exists detected_social_work_id bigint null,
  add column if not exists status text null,
  add column if not exists error_code text null,
  add column if not exists routing_duration_ms integer null,
  add column if not exists db_duration_ms integer null,
  add column if not exists openai_duration_ms integer null,
  add column if not exists file_search_duration_ms integer null,
  add column if not exists vision_duration_ms integer null,
  add column if not exists estimated_cost_usd numeric(14,8) null;

create index if not exists idx_assistant_query_log_created_at on public.assistant_query_log(created_at desc);
create index if not exists idx_assistant_query_log_route on public.assistant_query_log(route);
create index if not exists idx_assistant_query_log_social_work on public.assistant_query_log(social_work_id);
create index if not exists idx_assistant_query_log_has_image on public.assistant_query_log(has_image);

create table if not exists public.assistant_quality_event (
  id bigint generated by default as identity primary key,
  assistant_query_log_id bigint null references public.assistant_query_log(id) on delete set null,
  conversation_id uuid null,
  branch_id bigint null,
  social_work_id bigint null,
  event_type text not null,
  severity text not null default 'INFO' check (severity in ('INFO','WARNING','HIGH','CRITICAL')),
  message text null,
  metadata jsonb not null default '{}'::jsonb,
  resolved boolean not null default false,
  resolved_at timestamptz null,
  created_at timestamptz not null default now()
);

create index if not exists idx_assistant_quality_event_created_at on public.assistant_quality_event(created_at desc);
create index if not exists idx_assistant_quality_event_type on public.assistant_quality_event(event_type);
create index if not exists idx_assistant_quality_event_severity on public.assistant_quality_event(severity);

create table if not exists public.assistant_feedback (
  id bigint generated by default as identity primary key,
  assistant_query_log_id bigint null references public.assistant_query_log(id) on delete cascade,
  user_id uuid null,
  branch_id bigint null,
  rating text not null check (rating in ('UP','DOWN','REVIEW')),
  category text null,
  comment text null,
  created_at timestamptz not null default now()
);

create index if not exists idx_assistant_feedback_created_at on public.assistant_feedback(created_at desc);
create index if not exists idx_assistant_feedback_log_id on public.assistant_feedback(assistant_query_log_id);