BEGIN;
CREATE TABLE IF NOT EXISTS public.branch_notices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (char_length(trim(title)) BETWEEN 3 AND 140),
  body text NOT NULL CHECK (char_length(trim(body)) BETWEEN 3 AND 4000),
  severity text NOT NULL DEFAULT 'INFO' CHECK (severity IN ('INFO','IMPORTANT','URGENT')),
  all_branches boolean NOT NULL DEFAULT false,
  published boolean NOT NULL DEFAULT true,
  created_by uuid NOT NULL REFERENCES public.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  archived_at timestamptz,
  CONSTRAINT branch_notices_archived_chk CHECK (NOT (published AND archived_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS public.branch_notice_targets (
  notice_id bigint NOT NULL REFERENCES public.branch_notices(id) ON DELETE CASCADE,
  branch_id bigint NOT NULL REFERENCES public.branches(id),
  PRIMARY KEY(notice_id,branch_id)
);
CREATE INDEX IF NOT EXISTS branch_notice_targets_branch_idx ON public.branch_notice_targets(branch_id);
CREATE TABLE IF NOT EXISTS public.branch_notice_ack (
  notice_id bigint NOT NULL REFERENCES public.branch_notices(id) ON DELETE CASCADE,
  device_id bigint NOT NULL REFERENCES public.branch_devices(id),
  branch_id bigint NOT NULL REFERENCES public.branches(id),
  acknowledged_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(notice_id,device_id)
);
CREATE INDEX IF NOT EXISTS branch_notice_ack_branch_idx ON public.branch_notice_ack(branch_id);
CREATE INDEX IF NOT EXISTS branch_notices_active_idx ON public.branch_notices(published,created_at DESC);
-- Service role is used by server API; do not allow client-side access.
ALTER TABLE public.branch_notices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.branch_notice_targets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.branch_notice_ack ENABLE ROW LEVEL SECURITY;
COMMIT;
